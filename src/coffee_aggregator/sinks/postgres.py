#: One row per product per UTC day. ``seen_on`` is generated by the database
#: from ``seen_at``, and the unique index over it is what this conflicts on:
#: Lambda retries an async invocation twice by itself, and a retried crawl must
#: refresh the day it already wrote instead of appending a second one.
PRICE_HISTORY_SQL = (
    f"INSERT INTO price_history (site, external_id, seen_at, "  # noqa: S608  (a module constant)
    f"{', '.join(PRICE_HISTORY_COLUMNS[2:])}) "
    f"VALUES (%s, %s, now(), {', '.join(['%s'] * (len(PRICE_HISTORY_COLUMNS) - 2))}) "
    "ON CONFLICT (site, external_id, seen_on) DO UPDATE SET seen_at = now(), "
    + ", ".join(f"{column} = EXCLUDED.{column}" for column in PRICE_HISTORY_COLUMNS[2:])
)

